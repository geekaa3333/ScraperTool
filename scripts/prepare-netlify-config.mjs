#!/usr/bin/env node
/**
 * Generate netlify.toml from netlify.toml.template with a concrete backend URL.
 *
 * Why this exists
 * ---------------
 * Netlify does NOT substitute `${VAR}` in redirect targets. That was verified
 * against the live project, not assumed: with `BACKEND_URL` set both as a site
 * environment variable and in the process environment, the deployed redirect
 * still read `to = "${BACKEND_URL}/api/:splat"` literally. Because that is a
 * relative URL, Netlify resolved it against the site itself and every `/api/*`
 * request 404'd with Netlify's own "Page not found" page — a confusing failure
 * that looks like a missing backend when it is really an unsubstituted
 * variable.
 *
 * So the value is resolved here, at deploy time, and written into the config
 * that Netlify actually reads. The backend hostname is not a secret — it is a
 * public route the proxy already exposes — and keeping it out of version
 * control means one repository can target different environments.
 *
 * Usage:
 *   BACKEND_URL=https://api.example.com node scripts/prepare-netlify-config.mjs
 *
 * Refuses to write a config with a missing or malformed backend URL, so a
 * broken deploy fails here with a clear message rather than going live 404ing.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const TEMPLATE = join(root, 'netlify.toml.template');
const OUTPUT = join(root, 'netlify.toml');

const backendUrl = (process.env.BACKEND_URL ?? '').trim();

/**
 * Offline mode.
 *
 * Used when no backend exists yet. The alternative — leaving whatever the last
 * deploy happened to point at — is how a probe host ends up serving real users'
 * traffic. This makes the unset state explicit and serves a clear JSON error
 * instead of a confusing third-party page.
 */
const OFFLINE = backendUrl === 'offline';

if (!backendUrl) {
  console.error(
    'BACKEND_URL is not set.\n' +
    'The API proxy needs a concrete backend origin, for example:\n' +
    '  BACKEND_URL=https://api.example.com npm run deploy:netlify',
  );
  process.exit(1);
}

if (OFFLINE) {
  const template = readFileSync(TEMPLATE, 'utf8');
  const lines = template.split('\n');
  const start = lines.findIndex((line) => /^\s*from\s*=\s*"\/api\/\*"/.test(line));
  if (start < 0) {
    console.error('Template is missing the /api/* redirect rule.');
    process.exit(1);
  }
  // Replace the whole redirect block (header + from/to/status/force) with one
  // that serves the offline stub. Line-based so indentation or comment changes
  // in the template cannot silently stop it matching.
  let end = start;
  while (end < lines.length && !/^\s*force\s*=/.test(lines[end])) end += 1;
  const replacement = [
    '[[redirects]]',
    '  from = "/api/*"',
    '  to = "/api-offline.json"',
    '  status = 503',
    '  force = true',
  ];
  // Replace from the [[redirects]] header through the `force` line, inclusive.
  lines.splice(start - 1, end - start + 2, ...replacement);

  const offlineConfig = lines
    .join('\n')
    .replace(/__BACKEND_URL__/g, 'http://127.0.0.1:4310')
    .replace(/__GENERATED_NOTE__/g, 'offline mode - no backend configured');

  if (/^\s*to\s*=\s*"[^"]*\$\{/.test(offlineConfig)) {
    console.error('Offline config still contains an unexpanded reference.');
    process.exit(1);
  }
  writeFileSync(OUTPUT, offlineConfig);
  console.log('netlify.toml written in OFFLINE mode: /api/* returns 503 with an explanation.');
  console.log('  Set BACKEND_URL=https://your-api and redeploy once the API is live.');
  process.exit(0);
}

let parsed;
try {
  parsed = new URL(backendUrl);
} catch {
  console.error(`BACKEND_URL is not a valid URL: ${backendUrl}`);
  process.exit(1);
}

if (parsed.protocol !== 'https:' && parsed.hostname !== 'localhost' && parsed.hostname !== '127.0.0.1') {
  // Plain http is refused in production because the session cookie is Secure and
  // the browser would drop it, which presents as a login that never sticks.
  console.error(`BACKEND_URL must be https in production (got ${parsed.protocol}//${parsed.hostname}).`);
  process.exit(1);
}

const origin = parsed.origin;

if (!existsSync(TEMPLATE)) {
  console.error(`Template not found: ${TEMPLATE}`);
  process.exit(1);
}

const template = readFileSync(TEMPLATE, 'utf8');

if (!template.includes('__BACKEND_URL__')) {
  console.error('Template is missing the __BACKEND_URL__ placeholder.');
  process.exit(1);
}

const rendered = template
  .replaceAll('__BACKEND_URL__', origin)
  .replace(/__GENERATED_NOTE__/g, `generated by scripts/prepare-netlify-config.mjs for ${origin}`);

// Check the redirect targets rather than the whole file: a comment may quote
// `${BACKEND_URL}` while explaining the very problem this script prevents, and
// flagging that as a failure would make the file impossible to document.
const redirectTargets = [...rendered.matchAll(/^\s*to\s*=\s*"([^"]*)"/gm)].map((m) => m[1]);
const unexpanded = redirectTargets.filter((target) => target.includes('${') || target.includes('__'));
if (unexpanded.length > 0) {
  console.error(
    'Rendered redirect still contains an unexpanded reference:\n' +
    unexpanded.map((t) => `  to = "${t}"`).join('\n') +
    '\nNetlify will not substitute it; the API proxy would 404.',
  );
  process.exit(1);
}

writeFileSync(OUTPUT, rendered);
console.log(`netlify.toml written with BACKEND_URL=${origin}`);
console.log(`  proxy: ${origin}/api/*  ->  the Netlify origin`);